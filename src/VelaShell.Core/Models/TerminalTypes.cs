namespace VelaShell.Core.Models;

/// <summary>
/// 可向对端宣告的 <c>TERM</c> 档位清单 —— 设置页的全局下拉与连接配置里的会话级覆盖共用同一张表。
/// </summary>
/// <remarks>
/// <para>
/// 两处各抄一份的话,连接配置里迟早会出现仿真器根本不认识的档位(<c>linux</c> 就这么混进去过),
/// 或是少掉设置页里选得到的那几档;而"全局选得到、单条配置里选不到"是很难被发现的不一致。
/// </para>
/// <para>
/// 表里的每个名字都必须能被 <c>TerminalTypeExtensions.FromTermName</c> 认出来 ——
/// 认不出来的名字会被静默当成 <c>xterm-256color</c>,于是下拉里选了 A、实际发出去的是 B。
/// </para>
/// <para>
/// <b>这个值到底影响什么</b>,三件事一起变,不只是一个环境变量:
/// </para>
/// <list type="number">
/// <item>发给对端的 <c>TERM</c>(SSH 开 PTY 时送、本地终端写进环境):远端程序据此查 terminfo,
/// 决定用哪套转义序列画界面。远端没有对应 terminfo 条目时,vim / tmux / less 这类程序会报
/// <c>unknown terminal type</c> 或干脆退回最笨的画法。</item>
/// <item>设备属性(DA / DA2)应答:程序拿它探终端能力。宣示成 vt220 就别指望对方再发 Sixel。</item>
/// <item>本地仿真器自身的行为:VT52 会切到前 ANSI 的解析模式;而 256 色 / 真彩色
/// (<c>SGR 38/48;5</c> 与 <c>;2</c>)只在带色档位上生效,其余档位一律忽略那些参数
/// (基础 16 色的 <c>SGR 30-37</c> 不受影响)。</item>
/// </list>
/// <para>
/// <b>怎么选</b>:除非对端明确要求,否则一律用首项。往下调只有一个理由 ——
/// 远端认不出更高的档位(老 Unix、精简容器镜像、串口后面的硬件设备),
/// 而不是"调低一点更保险":降档只会让远端少用几种能力,画面反而更差。
/// </para>
/// </remarks>
public static class TerminalTypes
{
    /// <summary>可选终端类型;推荐项 <c>xterm-256color</c> 置首,其余按能力从高到低。</summary>
    public static string[] All { get; } =
        [
            // 默认与绝大多数场景的正解:256 色 + 真彩色。现代 Linux/BSD/macOS 的 terminfo 都带这条,
            // tmux、vim、bat、starship 一类程序也是按它来决定敢不敢上色。
            "xterm-256color",

            // 远端 terminfo 里没有 xterm-256color 时的退路(老 AIX / Solaris / HP-UX、
            // 剪过 ncurses 数据库的精简容器镜像)。仍是 xterm 家族,只是对外只宣示 8/16 色,
            // 程序会自己降级;比顶着一个查不到的 TERM 让 vim 报错强。
            "xterm",

            // 以下为 DEC VT 家族 —— 给的是"我就是这台古董机器"的承诺,面向按 VT 规格写死的
            // 老程序与硬件:串口/Console 后面的交换机、UPS、机床、银行与电信的字符终端程序。
            // 连普通 Linux 主机时不要选:远端会照着几十年前的能力集画界面,颜色和边框都会缩水。

            // VT500 系列高端型号:多会话、最全的显示扩展。要求严格 DEC 兼容、且对方认得 vt520 时才用。
            "vt520",

            // VT400 系列:多会话、左右边距(DECLRMM)等。一些工业与主机侧的终端程序按 vt420 写死。
            "vt420",

            // VT300 系列里带 Sixel 图形的型号。远端要靠 DA 应答判断"能不能发图"时选它;
            // 注意这只是对外的宣示,真正画不画得出来取决于渲染层。
            "vt340",

            // VT300 系列基础款:彩色、8 位控制。介于 vt220 与 vt340 之间的折中档。
            "vt320",

            // DEC 家族里最常见的一档,也是降档时的首选:8 位控制、DRCS、可编程功能键(UDK)。
            // 网络设备 console、堡垒机、老 Unix 上的 curses 程序大多只按 vt220 调过。
            // 注意它已不在带色档位里:256 色 / 真彩色的转义会被忽略。
            "vt220",

            // VT100 的增强型,多了插入/删除行列(IL/DL/ICH/DCH)。只在对端点名 vt102 时用。
            "vt102",

            // ANSI/VT 转义序列的基线,几乎没有东西不认它 —— 别的档位都试不通时的保底选择。
            // 无色、无扩展,画面朴素但不会乱。
            "vt100",

            // 前 ANSI 时代的 DEC 终端:转义序列与上面那些「完全是两套」(光标是 ESC A/B/C/D,
            // 没有 CSI、没有颜色),选中后本地仿真器会切进 VT52 解析模式。
            // 只有在对端确实是一台 VT52 或点名要 VT52 时才选 —— 拿它连普通 Linux,
            // 满屏 ANSI 序列会原样显示成乱码。
            "vt52"
        ];
}
